/**
 * 计算玩家牌风
 * @param {object} extended 牌谱屋 player_extended_stats（中文键）
 * @param {number|string} mode 4 或 3
 * @param {number} [count] 对局场次，用于样本量门槛
 * @returns {{name:string, x:number, y:number, cluster:number}|null} 数据不足或字段缺失时返回 null
 */
export function computePlayStyle (extended, mode, count) {
  const m = String(mode) === '3' ? 3 : 4
  const P = STYLE_PARAMS[m]
  if (!P || !extended) return null
  if ((count || 0) < MIN_GAMES_FOR_STYLE) return null

  // z-score 标准化；任一特征缺失则不判定（本地兜底路径只有 3 个字段）
  const z = []
  for (const f of STYLE_FEATURES) {
    const v = extended[f]
    const st = P.stats[f]
    if (typeof v !== 'number' || !isFinite(v) || v === 0 || !st) return null
    let zi = (v - st.mean) / st.std
    if (zi > Z_CLAMP) zi = Z_CLAMP
    else if (zi < -Z_CLAMP) zi = -Z_CLAMP
    z.push(zi)
  }

  // 投影到 2 维
  let x = 0, y = 0
  for (let i = 0; i < z.length; i++) {
    x += z[i] * P.pc1[i]
    y += z[i] * P.pc2[i]
  }

  // 取最近聚类中心
  let best = 0, bestD = Infinity
  for (let c = 0; c < P.centers.length; c++) {
    const d = (x - P.centers[c][0]) ** 2 + (y - P.centers[c][1]) ** 2
    if (d < bestD) { bestD = d; best = c }
  }

  return { name: P.names[best], x, y, cluster: best }
}
